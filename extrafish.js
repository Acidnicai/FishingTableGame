var EXTRA_FISH = [];

function addFish(scene, rows) {
  const jinOf = { t: [0.02, 0.08], s: [0.12, 0.55], m: [0.4, 2.2], l: [2, 12], h: [8, 40] };
  rows.forEach((row, index) => {
    const band = index % 10;
    const rarity = band === 9 ? 'legendary' : band === 8 ? 'rare' : band >= 5 ? 'uncommon' : 'common';
    const chance = rarity === 'legendary' ? 0.55 : rarity === 'rare' ? 2.2 : rarity === 'uncommon' ? 4.5 : 8;
    EXTRA_FISH.push({
      id: row[0],
      name: row[1],
      rarity,
      art: 'fish',
      chance,
      jin: jinOf[row[7]] || [0.2, 1],
      color: '#c8b090',
      scenes: [scene],
      where: row[2],
      water: row[3],
      size: row[4],
      line: row[5],
      sci: row[6],
    });
  });
}

